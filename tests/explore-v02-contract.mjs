import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const html=fs.readFileSync(new URL('../docs/explore-v02.html',import.meta.url),'utf8');
const script=html.match(/<script type="module">([\s\S]*?)<\/script>/)?.[1];
assert(script,'required V0.2 module code');
const noImport=script.replace(/^import \* as T from .*?;$/m,'');
new vm.SourceTextModule(noImport);
const roadsSrc=script.match(/const roads=(\[[\s\S]*?\]);\nconst lines=/)?.[1];
assert(roadsSrc,'road layout is declared');
const roads=vm.runInNewContext(roadsSrc);
const yes=(label,cond)=>{assert(cond,label);console.log('PASS '+label)};
yes('3km by 3km extent',script.includes('worldSize=3000,HALF=1500'));
yes('multiple connected routes',roads.length>=9);
yes('road paths include 3D xyz elevation',roads.every(r=>r.pts.every(p=>p.length===3)));
yes('road paths are within map bounds',roads.every(r=>r.pts.every(p=>Math.abs(p[0])<=1450&&Math.abs(p[1])<=1450)));
const m=roads.find(x=>x.name.includes('上山')),d=roads.find(x=>x.name.includes('下山'));
yes('mountain ascends to approximately 320m',m?.pts.at(-1)?.[2]===320&&m.pts[0][2]<8);
yes('mountain descends from 320m',d?.pts[0]?.[2]===320&&d.pts.at(-1)?.[2]<8);
let reversals=0,prev=0;for(let i=1;i<m.pts.length;i++){const delta=m.pts[i][0]-m.pts[i-1][0];const sign=Math.sign(delta);if(prev&&sign!==prev)reversals++;prev=sign}
yes('mountain switchbacks reverse laterally at least 4 times',reversals>=4);
yes('road meshes use elevation rather than fixed flat Y',script.includes('p.y+.11'));
yes('car follows 3D road height',script.includes('surface.y+1.2'));
yes('lake has a rough surface route',roads.some(r=>r.kind==='gravel'&&r.name.includes('湖畔')));
yes('wheel/chassis bump depends on actual gravel',script.includes("surface.kind==='gravel'&&surface.distance<13")&&script.includes('chassis.position.y=state.shake'));
yes('camera bounce is smaller than car bounce',script.includes('pos.y+=state.vertical*.22'));
yes('left-right steering stays correct',script.includes('state.heading-=state.steer*dt'));
yes('touch buttons present',["left","right","gas","brake"].every(k=>html.includes('data-key="'+k+'"')));
yes('instanced trees minimize draw calls',script.includes('new T.InstancedMesh'));
yes('independent preview never accesses production save',!/(localStorage|r5_racing_saves|coins_balance|r5-gateway|owned\.frag_)/.test(script));
console.log('V0.2 contract checks 16/16 PASS');
